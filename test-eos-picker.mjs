import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {CueCatalogue} from './cue-catalogue.mjs';
const events={},elements={};
for(const id of ['cue','cue-name','go','result'])elements['#'+id]={value:'',textContent:'',disabled:false,classList:{toggle:()=>{}},addEventListener:(type,fn)=>events[id+':'+type]=fn,focus:()=>{}};
const document={querySelector:s=>elements[s],querySelectorAll:()=>[],addEventListener:(type,fn)=>events[type]=fn};
let response={ok:true,json:async()=>({sent:true,list:2})},requests=[];
const ctx=vm.createContext({document,window:{matchMedia:()=>({matches:false})},AbortSignal,fetch:async(url,opts)=>{requests.push(JSON.parse(opts.body));return response;}});
const js=fs.readFileSync(new URL('./eos.js',import.meta.url),'utf8');
vm.runInContext(js.slice(0,js.indexOf('async function poll()')),ctx);
vm.runInContext('connected=true;revision=9;',ctx);
const target={closest:()=>null};
const key=(key,extra={})=>events.keydown({key,target,preventDefault:()=>{},...extra});
key('0');key('.');key('3');assert.equal(elements['#cue'].value,'0.3');
key('Backspace');assert.equal(elements['#cue'].value,'0.');key('3');
key('Enter');await new Promise(r=>setImmediate(r));
assert.deepEqual(requests,[{cue:'0.3',revision:9}]);
assert.equal(elements['#cue'].value,'','Successful Go must clear the entry');
assert.equal(elements['#go'].disabled,true);
key('1');key('3');assert.equal(elements['#cue'].value,'13','Ready for the next number');
response={ok:false,json:async()=>({error:'Cue 2/13 does not exist'})};
key('Enter');await new Promise(r=>setImmediate(r));
assert.equal(elements['#cue'].value,'13','Errors must retain the entry');
assert.equal(elements['#result'].textContent,'Cue 2/13 does not exist');
key('Escape');assert.equal(elements['#cue'].value,'');
key('7',{ctrlKey:true});assert.equal(elements['#cue'].value,'','Keep keyboard shortcuts intact');
key('Enter',{repeat:true});assert.equal(requests.length,2,'Held Enter must not resend');

const c=new CueCatalogue();assert.equal(c.lookup(2,'0.3'),'loading');
c.begin(2,1);c.add({list:2,part:0,number:'0.3',name:'Decimal'},0);
assert.equal(c.lookup(2,'0.300'),'found');assert.equal(c.lookup(2,'13'),'missing');
c.begin(2,2);assert.equal(c.lookup(2,'13'),'loading','Do not claim missing while refreshing');
assert.equal(c.lookup(2,'0.3'),'found','Known cues remain usable while refreshing');
c.reconnect([2]);assert.equal(c.lookup(2,'0.3'),'found');
c.clear();assert.equal(c.lookup(2,'0.3'),'loading');
console.log('PASS: keyboard/decimal entry, Enter, clear after success, retained input and missing-cue notice, Escape, shortcut/repeat protection, catalogue validation');
